# UNIVERSITY-CLUSTER BOOTSTRAP — MATRIX + THREADS
# ============================================================

def prepare_bootstrap_matrices(d):
    """Precompute one NumPy regression matrix per event time.

    Pandas pivots/differences are executed once per outcome/scale, not once
    per bootstrap replication.  Each event-time matrix contains one row per
    university with complete inputs for the MAIN_CONTROLS specification.

    Returns
    -------
    matrices : dict
        tau -> {year, X, y, cluster_idx, treated}
    cluster_table : pd.DataFrame
        One row per university in the bootstrap population.
    msg : str
    """
    change_frames, msg = prepare_dynamic_changes(d)

    if not change_frames:
        return {}, pd.DataFrame(), msg

    cluster_table = (
        d[["id", "treated"]]
        .drop_duplicates(subset=["id"])
        .reset_index(drop=True)
    )

    if cluster_table["id"].duplicated().any():
        raise ValueError("Bootstrap cluster IDs are not unique.")

    cluster_lookup = {
        uid: i
        for i, uid in enumerate(cluster_table["id"].tolist())
    }

    matrices = {}
    required = ["dy", "treated", *MAIN_CONTROLS]

    for tau in sorted(change_frames):
        year = change_frames[tau]["year"]
        sub = change_frames[tau]["data"]

        use = sub.dropna(subset=required).copy()
        if use.empty:
            continue

        cluster_idx = use["id"].map(cluster_lookup)
        if cluster_idx.isna().any():
            raise ValueError(
                f"Bootstrap cluster mapping failed for event time {tau}."
            )

        treated = use["treated"].to_numpy(dtype=np.int8)
        x = np.column_stack([
            np.ones(len(use), dtype=float),
            treated.astype(float),
            *[
                use[name].to_numpy(dtype=float)
                for name in MAIN_CONTROLS
            ],
        ])
        y = use["dy"].to_numpy(dtype=float)

        matrices[tau] = {
            "year": int(year),
            "X": np.ascontiguousarray(x, dtype=float),
            "y": np.ascontiguousarray(y, dtype=float),
            "cluster_idx": cluster_idx.to_numpy(dtype=np.int32),
            "treated": treated,
        }

    return matrices, cluster_table, "ok"


def build_bootstrap_weights(cluster_table, reps, seed):
    """Generate cluster-bootstrap multiplicities for all replications.

    Sampling is stratified exactly as in the original code: treated
    universities are resampled from treated universities and controls from
    controls, each with replacement and keeping the original group size.

    Integer multiplicities are frequency weights and are algebraically
    equivalent to physically duplicating the university rows before OLS.
    """
    treated_flag = cluster_table["treated"].to_numpy(dtype=np.int8)
    treated_idx = np.flatnonzero(treated_flag == 1)
    control_idx = np.flatnonzero(treated_flag == 0)

    if len(treated_idx) == 0 or len(control_idx) == 0:
        return None

    rng = np.random.default_rng(seed)
    weights = np.zeros(
        (reps, len(cluster_table)),
        dtype=np.int16,
    )

    # Multinomial counts are the compact matrix representation of drawing
    # len(group) university IDs with replacement from a uniform group.
    weights[:, treated_idx] = rng.multinomial(
        n=len(treated_idx),
        pvals=np.full(len(treated_idx), 1.0 / len(treated_idx)),
        size=reps,
    ).astype(np.int16, copy=False)

    weights[:, control_idx] = rng.multinomial(
        n=len(control_idx),
        pvals=np.full(len(control_idx), 1.0 / len(control_idx)),
        size=reps,
    ).astype(np.int16, copy=False)

    return weights


def fit_weighted_att_matrix(x, y, treated, row_weights):
    """Frequency-weighted OLS ATT for one event time / bootstrap draw."""
    positive = row_weights > 0
    if not positive.any():
        return np.nan

    t = treated[positive]
    if not np.any(t == 1) or not np.any(t == 0):
        return np.nan

    xv = x[positive]
    yv = y[positive]
    sqrt_w = np.sqrt(row_weights[positive].astype(float))

    xw = xv * sqrt_w[:, None]
    yw = yv * sqrt_w

    if np.linalg.matrix_rank(xw) < xw.shape[1]:
        return np.nan

    coef = np.linalg.lstsq(xw, yw, rcond=None)[0]
    return float(coef[1])


def _bootstrap_matrix_chunk(weight_chunk, matrix_items):
    """Run a block of bootstrap replications in one worker thread."""
    n_rep = weight_chunk.shape[0]
    n_tau = len(matrix_items)
    result = np.full((n_rep, n_tau), np.nan, dtype=float)

    # Loop over event times outside the replication loop so matrix data stay
    # hot in cache.  No pandas operations occur inside this worker.
    for j, (_, item) in enumerate(matrix_items):
        x = item["X"]
        y = item["y"]
        treated = item["treated"]
        cluster_idx = item["cluster_idx"]
        tau_weights = weight_chunk[:, cluster_idx]

        for b in range(n_rep):
            result[b, j] = fit_weighted_att_matrix(
                x,
                y,
                treated,
                tau_weights[b],
            )

    return result


def bootstrap_dynamic(
    d,
    reps=BOOT_REPS,
    seed=RANDOM_SEED,
    n_threads=BOOT_THREADS,
):
    """University-cluster bootstrap using cached matrices and worker threads.

    The point estimates and robustness specifications are still computed by
    `compute_att_dynamic`.  Only the main ATT bootstrap is accelerated, which
    is exactly what the original implementation used to construct se_boot and
    the percentile confidence interval.
    """
    t0 = time.perf_counter()

    base_att, _ = compute_att_dynamic(d)
    if base_att is None or base_att.empty:
        return base_att

    matrices, cluster_table, msg = prepare_bootstrap_matrices(d)
    if not matrices:
        print(f"[BOOT] Matrix preparation failed: {msg}")
        return base_att

    weights = build_bootstrap_weights(
        cluster_table,
        reps=reps,
        seed=seed,
    )
    if weights is None:
        return None

    matrix_items = [
        (tau, matrices[tau])
        for tau in sorted(matrices)
    ]
    tau_to_col = {
        tau: j
        for j, (tau, _) in enumerate(matrix_items)
    }

    workers = max(1, min(int(n_threads), int(reps)))
    chunks = [
        chunk
        for chunk in np.array_split(weights, workers, axis=0)
        if len(chunk) > 0
    ]

    print(
        f"[BOOT] {reps} reps | {workers} threads | "
        f"{len(cluster_table)} universities | matrix mode"
    )

    # NumPy linear algebra releases the GIL.  Limiting BLAS to one internal
    # thread avoids N worker threads each creating their own BLAS thread pool.
    blas_context = (
        threadpool_limits(limits=1, user_api="blas")
        if threadpool_limits is not None
        else nullcontext()
    )

    with blas_context:
        if workers == 1:
            boot_matrix = _bootstrap_matrix_chunk(
                chunks[0],
                matrix_items,
            )
        else:
            with ThreadPoolExecutor(max_workers=workers) as executor:
                parts = list(
                    executor.map(
                        lambda chunk: _bootstrap_matrix_chunk(
                            chunk,
                            matrix_items,
                        ),
                        chunks,
                    )
                )
            boot_matrix = np.vstack(parts)

    out = base_att.copy()

    for i, row in out.iterrows():
        tau = row["event_time"]
        col = tau_to_col.get(tau)

        if col is None:
            vals = np.asarray([], dtype=float)
        else:
            vals = boot_matrix[:, col]
            vals = vals[np.isfinite(vals)]

        if len(vals) >= 30:
            out.loc[i, "se_boot"] = vals.std(ddof=1)
            out.loc[i, "ci_low"] = np.quantile(vals, 0.025)
            out.loc[i, "ci_high"] = np.quantile(vals, 0.975)

        out.loc[i, "boot_reps_valid"] = len(vals)

    # Joint covariance of the event-study coefficients.  HonestDiD and
    # pretrends require the full matrix, not only pointwise standard errors.
    joint_valid = np.all(np.isfinite(boot_matrix), axis=1)
    joint_draws = boot_matrix[joint_valid]
    if joint_draws.shape[0] >= 30:
        tau_order = [tau for tau, _ in matrix_items]
        covariance = np.cov(joint_draws, rowvar=False, ddof=1)
        covariance = np.atleast_2d(covariance)
        out.attrs["bootstrap_vcov"] = pd.DataFrame(
            covariance,
            index=tau_order,
            columns=tau_order,
        )
        out.attrs["bootstrap_joint_reps_valid"] = int(joint_draws.shape[0])
    else:
        out.attrs["bootstrap_vcov"] = pd.DataFrame()
        out.attrs["bootstrap_joint_reps_valid"] = int(joint_draws.shape[0])

    elapsed = time.perf_counter() - t0
    print(f"[BOOT] Completed in {elapsed:.2f} s")

    return out


