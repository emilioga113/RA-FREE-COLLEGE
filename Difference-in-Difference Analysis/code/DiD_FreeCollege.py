# PRICE INDEX
# ============================================================

def build_price_index(df, year_col):
    """
    Price index normalized to 2015 = 1.

    Inflation_WB is assumed to be expressed in decimals:
        0.043 = 4.3%
    """

    if INFLATION_COL not in df.columns:
        raise KeyError(
            f"{INFLATION_COL} not found."
        )

    inflation = df[
        [
            year_col,
            INFLATION_COL,
        ]
    ].copy()

    inflation[INFLATION_COL] = to_numeric_finite(
        inflation[INFLATION_COL]
    )

    inflation = (
        inflation
        .groupby(year_col)[INFLATION_COL]
        .median()
        .sort_index()
    )

    years = sorted(
        int(y)
        for y in inflation.index
        if pd.notna(y)
    )

    if BASE_YEAR not in years:
        raise ValueError(
            f"Inflation data do not contain {BASE_YEAR}."
        )

    price_index = {
        BASE_YEAR: 1.0
    }

    # Forward from 2015
    for year in [
        y
        for y in years
        if y > BASE_YEAR
    ]:
        previous = year - 1

        if previous not in price_index:
            continue

        pi = inflation.get(year, np.nan)

        if pd.isna(pi) or pi <= -1:
            continue

        price_index[year] = (
            price_index[previous]
            * (1 + pi)
        )

    # Backward from 2015
    for year in sorted(
        [
            y
            for y in years
            if y < BASE_YEAR
        ],
        reverse=True,
    ):
        next_year = year + 1

        if next_year not in price_index:
            continue

        pi_next = inflation.get(
            next_year,
            np.nan,
        )

        if pd.isna(pi_next) or pi_next <= -1:
            continue

        price_index[year] = (
            price_index[next_year]
            / (1 + pi_next)
        )

    return (
        pd.DataFrame({
            year_col: list(price_index.keys()),
            "price_index_2015": list(price_index.values()),
        })
        .sort_values(year_col)
    )


