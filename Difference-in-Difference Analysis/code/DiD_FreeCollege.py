def read_panel(path, name_map):
    if not os.path.exists(path):
        raise FileNotFoundError(
            f"File not found:\n{path}"
        )

    df = pd.read_csv(
        path,
        encoding="utf-8-sig",
    )

    id_col = (
        "Universidad_std"
        if "Universidad_std" in df.columns
        else df.columns[0]
    )

    year_col = (
        "Año"
        if "Año" in df.columns
        else df.columns[1]
    )

    df[id_col] = apply_name_mapping(
        df[id_col].astype(str),
        name_map,
    )

    df[year_col] = (
        to_numeric_finite(
            df[year_col]
        )
        .astype("Int64")
    )

    # Optional Sabat postgraduate outcomes. This merge preserves the Fitch
    # panel cardinality and leaves all existing financial columns untouched.
    df = merge_academic_outcomes(
        df,
        id_col=id_col,
        year_col=year_col,
        name_map=name_map,
    )

    required_controls = [
        ENROLLMENT_COL,
        ACCREDITATION_COL,
        ELIGIBILITY_COL,
        ELIGIBILITY_COVERAGE_COL,
    ]

    missing_controls = [
        col
        for col in required_controls
        if col not in df.columns
    ]

    if missing_controls:
        raise KeyError(
            f"Missing controls: {missing_controls}"
        )

    df = apply_and_validate_pucv_accreditation(
        df,
        id_col,
        year_col,
    )

    df = create_real_outcomes(
        df,
        id_col,
        year_col,
    )

    # --------------------------------------------------------
    # CONTROLS
    # --------------------------------------------------------

    df["enrollment_undergrad"] = to_numeric_finite(
        df[ENROLLMENT_COL]
    )

    df["log_enrollment_undergrad"] = np.where(
        df["enrollment_undergrad"] > 0,
        np.log(df["enrollment_undergrad"]),
        np.nan,
    )

    df["accreditation_years"] = to_numeric_finite(
        df[ACCREDITATION_COL]
    )

    df["accreditation_ge4"] = np.where(
        df["accreditation_years"].notna(),
        (
            df["accreditation_years"] >= 4
        ).astype(float),
        np.nan,
    )

    df["eligibility_proxy_10"] = (
        to_numeric_finite(
            df[ELIGIBILITY_COL]
        )
        / 10
    )

    df["eligibility_coverage_10"] = (
        to_numeric_finite(
            df[ELIGIBILITY_COVERAGE_COL]
        )
        / 10
    )

    # --------------------------------------------------------
    # WIDE -> LONG
    # --------------------------------------------------------

    id_vars = [
        id_col,
        year_col,
        "enrollment_undergrad",
        "log_enrollment_undergrad",
        "accreditation_years",
        "accreditation_ge4",
        "eligibility_proxy_10",
        "eligibility_coverage_10",
    ]

    # Preserve paper-descriptive university-year variables in the long panel.
    # They are repeated across outcomes but can be collapsed back to one
    # university-year row without imputation.
    for col in DESCRIPTIVE_EXTRA_COLS:
        if col in df.columns and col not in id_vars:
            id_vars.append(col)

    pieces = []

    for outcome, spec in OUTCOME_SPECS.items():
        source_col = spec["column"]

        if source_col not in df.columns:
            print(
                f"[MISSING] {outcome}: {source_col}"
            )
            continue

        tmp = df[id_vars].copy()
        tmp["indicator"] = outcome
        tmp["y"] = to_numeric_finite(
            df[source_col]
        )

        pieces.append(tmp)
        print(f"[OK] Outcome: {outcome}")

    if not pieces:
        raise ValueError(
            "No outcome variables available."
        )

    long = pd.concat(
        pieces,
        ignore_index=True,
    )

    long = long.rename(
        columns={
            id_col: "id",
            year_col: "t",
        }
    )

    long["id_norm"] = (
        long["id"]
        .map(norm_name)
    )

    return_cols = [
        "id",
        "id_norm",
        "t",
        "indicator",
        "y",
        "enrollment_undergrad",
        "log_enrollment_undergrad",
        "accreditation_years",
        "accreditation_ge4",
        "eligibility_proxy_10",
        "eligibility_coverage_10",
    ]

    return_cols.extend(
        col for col in DESCRIPTIVE_EXTRA_COLS
        if col in long.columns and col not in return_cols
    )

    return long[return_cols]


