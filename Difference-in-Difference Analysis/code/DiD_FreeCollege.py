def safe(s):
    return re.sub(r"[^\w\-]+", "_", str(s), flags=re.UNICODE).strip("_")


def strip_accents(s):
    if not isinstance(s, str):
        return s

    return "".join(
        c
        for c in unicodedata.normalize("NFD", s)
        if unicodedata.category(c) != "Mn"
    )


def norm_name(s):
    if s is None:
        return s

    s = strip_accents(str(s)).lower().strip()
    return re.sub(r"\s+", " ", s).replace(".", "")


def to_numeric_finite(s):
    s = pd.to_numeric(s, errors="coerce")
    return s.mask(~np.isfinite(s), np.nan)


def normalize_cohort_dict(cohorts, mapping):
    out = {}

    for university, year in cohorts.items():
        standard = mapping.get(norm_name(university), university)
        out[norm_name(standard)] = int(year)

    return out


