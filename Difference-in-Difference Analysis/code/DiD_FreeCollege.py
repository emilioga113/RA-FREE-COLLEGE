def load_name_mapping(path):
    if not os.path.exists(path):
        raise FileNotFoundError(
            f"No se encuentra el mapeo de universidades:\n{path}"
        )

    m = pd.read_csv(path, encoding="utf-8-sig")

    if "Final_Standard" not in m.columns:
        raise ValueError(
            "El mapeo no contiene la columna Final_Standard."
        )

    mapping = {}

    source_columns = [
        "Universidad_key",
        "Universidad_raw",
        "CNED 2011-2022",
        "Suggested_Standard",
        "Final_Standard",
    ]

    for _, row in m.iterrows():
        standard = row["Final_Standard"]

        if pd.isna(standard) or not str(standard).strip():
            continue

        standard = str(standard).strip()

        for col in source_columns:
            if (
                col in m.columns
                and pd.notna(row[col])
                and str(row[col]).strip()
            ):
                mapping[norm_name(row[col])] = standard

    return mapping


def apply_name_mapping(series, mapping):
    if not mapping:
        return series

    return series.map(
        lambda x: mapping.get(norm_name(x), x)
    )


