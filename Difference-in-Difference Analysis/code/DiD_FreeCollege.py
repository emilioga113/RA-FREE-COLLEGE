def apply_and_validate_pucv_accreditation(df, id_col, year_col):
    is_pucv = (
        df[id_col]
        .map(norm_name)
        .eq(norm_name(PUCV_NAME))
    )

    expected = df[year_col].map(
        PUCV_ACCREDITATION_BY_YEAR
    )

    mask = is_pucv & expected.notna()

    if not mask.any():
        raise ValueError(
            "PUCV no está presente en el panel Fitch."
        )

    existing = to_numeric_finite(
        df.loc[
            mask,
            ACCREDITATION_COL,
        ]
    )

    conflicts = (
        existing.notna()
        & existing.ne(expected.loc[mask])
    )

    if conflicts.any():
        bad = df.loc[
            mask
        ].loc[
            conflicts,
            [
                id_col,
                year_col,
                ACCREDITATION_COL,
            ],
        ]

        raise ValueError(
            "La acreditación PUCV contradice la cronología "
            f"esperada:\n{bad.to_string(index=False)}"
        )

    df.loc[
        mask,
        ACCREDITATION_COL,
    ] = existing.fillna(
        expected.loc[mask]
    )

    print(
        "[CHECK] PUCV accreditation: "
        "6 years (2011-2021), 7 years (2022)."
    )

    return df


