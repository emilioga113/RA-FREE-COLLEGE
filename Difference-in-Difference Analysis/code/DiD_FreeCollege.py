# ============================================================

def create_real_outcomes(df, id_col, year_col):
    """
    Monetary variables are converted to 2015 real values.

    Exact real log growth:

        Δln(Y_real)
        =
        Δln(Y_nominal) - ln(1 + inflation)
    """

    out = df.copy()

    price_index = build_price_index(
        out,
        year_col,
    )

    out = out.merge(
        price_index,
        on=year_col,
        how="left",
        validate="many_to_one",
    )

    if REVENUE_ALT_COL in out.columns:
        revenue_source = REVENUE_ALT_COL
    else:
        raise KeyError(
            f"{REVENUE_ALT_COL} not found."
        )

    required = [
        revenue_source,
        OPEX_NOMINAL_COL,
        CAPEX_STUDENT_NOMINAL_COL,
        INFLATION_COL,
    ]

    missing = [
        col
        for col in required
        if col not in out.columns
    ]

    if missing:
        raise KeyError(
            f"Missing monetary variables: {missing}"
        )

    for col in required:
        out[col] = to_numeric_finite(
            out[col]
        )

    # --------------------------------------------------------
    # REAL LEVELS
    # --------------------------------------------------------

    out[REVENUE_REAL_COL] = (
        out[revenue_source]
        / out["price_index_2015"]
    )

    out[OPEX_REAL_COL] = (
        out[OPEX_NOMINAL_COL]
        / out["price_index_2015"]
    )

    out[CAPEX_REAL_COL] = (
        out[CAPEX_STUDENT_NOMINAL_COL]
        / out["price_index_2015"]
    )

    out = out.sort_values(
        [
            id_col,
            year_col,
        ]
    ).copy()

    # --------------------------------------------------------
    # REVENUE REAL LOG GROWTH
    # --------------------------------------------------------

    out["_log_revenue_nominal"] = np.where(
        out[revenue_source] > 0,
        np.log(out[revenue_source]),
        np.nan,
    )

    revenue_nominal_log_change = (
        out
        .groupby(id_col)["_log_revenue_nominal"]
        .diff()
    )

    valid_inflation = (
        out[INFLATION_COL] > -1
    )

    log_inflation_factor = pd.Series(
        np.nan,
        index=out.index,
        dtype=float,
    )

    log_inflation_factor.loc[
        valid_inflation
    ] = np.log1p(
        out.loc[
            valid_inflation,
            INFLATION_COL,
        ]
    )

    out[REVENUE_REAL_LOG_GROWTH_COL] = (
        revenue_nominal_log_change
        - log_inflation_factor
    )

    # --------------------------------------------------------
    # OPEX REAL LOG GROWTH
    # --------------------------------------------------------

    out["_log_opex_nominal"] = np.where(
        out[OPEX_NOMINAL_COL] > 0,
        np.log(out[OPEX_NOMINAL_COL]),
        np.nan,
    )

    opex_nominal_log_change = (
        out
        .groupby(id_col)["_log_opex_nominal"]
        .diff()
    )

    out[OPEX_REAL_LOG_GROWTH_COL] = (
        opex_nominal_log_change
        - log_inflation_factor
    )

    # Exact revenue growth in percentage terms
    out["Revenue Real Growth Computed (%)"] = (
        100
        * np.expm1(
            out[REVENUE_REAL_LOG_GROWTH_COL]
        )
    )

    return out.drop(
        columns=[
            "_log_revenue_nominal",
            "_log_opex_nominal",
        ]
    )



