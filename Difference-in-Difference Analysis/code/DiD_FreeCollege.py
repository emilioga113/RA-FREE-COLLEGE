def make_analysis_df(
    panel,
    outcome,
    cohorts_norm,
    exclude_closed=True,
):
    d = panel.loc[
        panel["indicator"].eq(outcome)
    ].copy()

    excluded_names = set(EXCLUDED_MAIN_SAMPLE)
    if exclude_closed:
        excluded_names.update(EXCLUDED_CLOSED_UNIVERSITIES)

    excluded_norm = {
        norm_name(name)
        for name in excluded_names
    }
    d = d.loc[
        ~d["id_norm"].isin(excluded_norm)
    ].copy()

    d = d.dropna(
        subset=[
            "id",
            "id_norm",
            "t",
        ]
    )

    if d.empty:
        return d

    d["actual_treatment_year"] = (
        d["id_norm"]
        .map(cohorts_norm)
    )

    target_cohort = (
        d["actual_treatment_year"]
        .eq(TREAT_YEAR)
    )

    never_treated = (
        d["actual_treatment_year"]
        .isna()
    )

    # 2016 treated + never-treated only.
    d = d.loc[
        target_cohort
        | never_treated
    ].copy()

    d["treated"] = (
        d["actual_treatment_year"]
        .eq(TREAT_YEAR)
        .astype(int)
    )

    d["event_time"] = (
        d["t"]
        - TREAT_YEAR
    )

    return d


