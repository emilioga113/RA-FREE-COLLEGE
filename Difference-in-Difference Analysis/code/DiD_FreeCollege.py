def print_cohort_diagnostics(
    cohorts_norm,
    name_map,
):
    counts = (
        pd.Series(
            list(
                cohorts_norm.values()
            )
        )
        .value_counts()
        .sort_index()
    )

    print(
        "\n[CHECK] Treatment cohorts:"
    )

    for year, n in counts.items():
        print(
            f" - {int(year)}: "
            f"{int(n)} universities"
        )

    n_target = sum(
        year == TREAT_YEAR
        for year in cohorts_norm.values()
    )

    print(
        f"\n[DESIGN] Target cohort {TREAT_YEAR}: "
        f"{n_target} universities."
    )

    print(
        "[DESIGN] Other treated cohorts "
        "are excluded from the control group."
    )

    pucv_standard = name_map.get(
        norm_name(PUCV_NAME),
        PUCV_NAME,
    )

    pucv_year = cohorts_norm.get(
        norm_name(
            pucv_standard
        )
    )

    if pucv_year != 2016:
        raise ValueError(
            "PUCV debe estar tratada en 2016, "
            f"pero aparece como {pucv_year}."
        )

    print(
        "[CHECK] PUCV treatment cohort: 2016."
    )


