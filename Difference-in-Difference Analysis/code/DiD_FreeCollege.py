def export_desc(
    d,
    ev,
    outcome,
    transformed=False,
):
    df = d.copy()

    df["event_time_ctrl"] = (
        df["t"]
        - TREAT_YEAR
    )

    idx = pd.Index(
        range(
            WINDOW[0],
            WINDOW[1] + 1,
        ),
        name="event_time",
    )

    global_stats = (
        df[
            df["event_time_ctrl"].between(
                WINDOW[0],
                WINDOW[1],
            )
        ]
        .groupby("event_time_ctrl")["y"]
        .agg(
            [
                "count",
                "mean",
                "median",
                "std",
                "min",
                "max",
            ]
        )
        .reindex(idx)
    )

    treated_mean = (
        df.loc[
            df["treated"] == 1
        ]
        .groupby("event_time")["y"]
        .mean()
        .rename("Treated")
        .reindex(idx)
    )

    control_mean = (
        df.loc[
            df["treated"] == 0
        ]
        .groupby("event_time_ctrl")["y"]
        .mean()
        .rename("Control")
        .reindex(idx)
    )

    treated_median = (
        df.loc[
            df["treated"] == 1
        ]
        .groupby("event_time")["y"]
        .median()
        .rename("Treated_median")
        .reindex(idx)
    )

    control_median = (
        df.loc[
            df["treated"] == 0
        ]
        .groupby("event_time_ctrl")["y"]
        .median()
        .rename("Control_median")
        .reindex(idx)
    )

    out = pd.concat(
        [
            global_stats,
            treated_mean,
            control_mean,
            treated_median,
            control_median,
        ],
        axis=1,
    )

    out["Diff_levels"] = (
        out["Treated"]
        - out["Control"]
    )

    out["Diff_medians"] = (
        out["Treated_median"]
        - out["Control_median"]
    )

    out = out.reset_index()

    suffix = (
        "_log"
        if transformed
        else ""
    )

    path = os.path.join(
        DESC_DIR,
        f"desc_dynamic_{safe(outcome)}{suffix}.xlsx",
    )

    with pd.ExcelWriter(path) as writer:
        out.to_excel(
            writer,
            sheet_name="stats_by_event_time",
            index=False,
        )

        ev.to_excel(
            writer,
            sheet_name="ATT_dynamic",
            index=False,
        )

    return path


