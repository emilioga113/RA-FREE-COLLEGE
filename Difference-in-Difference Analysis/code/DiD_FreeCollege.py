def make_transformed_outcome(d, outcome):
    out = d.copy()

    mode = OUTCOME_SPECS[
        outcome
    ]["transform"]

    y = to_numeric_finite(
        out["y"]
    )

    z = pd.Series(
        np.nan,
        index=y.index,
        dtype=float,
    )

    n_invalid = 0

    if mode == "identity":
        z = y.copy()
        label = OUTCOME_SPECS[outcome].get(
            "transform_label",
            "identity",
        )

    elif mode == "log":
        valid = (
            y.notna()
            & (y > 0)
        )

        z.loc[valid] = np.log(
            y.loc[valid]
        )

        n_invalid = int(
            (
                y.notna()
                & ~valid
            ).sum()
        )

        label = "log"

    elif mode == "log1p":
        # Sabat specification for non-negative count outcomes.
        # log1p(0) = 0, so universities with a true zero remain in the sample.
        valid = (
            y.notna()
            & (y >= 0)
        )

        z.loc[valid] = np.log1p(
            y.loc[valid]
        )

        n_invalid = int(
            (
                y.notna()
                & ~valid
            ).sum()
        )

        label = OUTCOME_SPECS[outcome].get(
            "transform_label",
            "log1p",
        )

    elif mode == "asinh":
        valid = y.notna()

        z.loc[valid] = np.arcsinh(
            y.loc[valid]
        )

        label = "asinh"

    elif mode == "asinh_pct":
        valid = y.notna()

        z.loc[valid] = np.arcsinh(
            y.loc[valid] / 100
        )

        label = "asinh(ratio/100)"

    else:
        raise ValueError(
            f"Unknown transformation mode: {mode}"
        )

    out["y"] = z

    return (
        out,
        mode,
        label,
        n_invalid,
    )


