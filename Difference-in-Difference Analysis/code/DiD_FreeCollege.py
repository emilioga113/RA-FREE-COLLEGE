def export_excluded_universities_descriptives(panel):
    """Describe the five closure/accreditation-risk control universities.

    The output stays in the existing summary-statistics directory and contains
    one compact summary sheet plus the underlying university-year records.
    Missing values remain missing and all statistics are calculated from the
    same prepared financial panel used by the DiD estimators.
    """
    excluded_norm = {
        norm_name(name)
        for name in EXCLUDED_CLOSED_UNIVERSITIES
    }

    base_columns = ["id", "id_norm", "t"]
    institutional_columns = [
        column
        for column in DESCRIPTIVE_EXTRA_COLS
        if column in panel.columns
    ]
    institutional = (
        panel[base_columns + institutional_columns]
        .drop_duplicates(subset=["id_norm", "t"])
    )
    financial = (
        panel.pivot_table(
            index=["id", "id_norm", "t"],
            columns="indicator",
            values="y",
            aggfunc="first",
        )
        .reset_index()
    )
    annual = institutional.merge(
        financial,
        on=["id", "id_norm", "t"],
        how="outer",
        validate="one_to_one",
    )
    annual = annual.loc[annual["id_norm"].isin(excluded_norm)].copy()
    annual = annual.sort_values(["id", "t"]).reset_index(drop=True)

    found = set(annual["id_norm"].dropna().unique())
    missing = sorted(excluded_norm - found)
    if missing:
        raise ValueError(
            "Excluded-university descriptive table is missing: "
            + ", ".join(missing)
        )

    reason_by_norm = {
        norm_name("Uniacc"): "Closure/accreditation loss; extreme margins",
        norm_name("Universidad del Pacifico"): "Closure/accreditation loss; per-student unit break",
        norm_name("Universidad de Las Ciencias de la Informática (UCINF)"):
            "Closure/accreditation loss; per-student unit break",
        norm_name("Universidad ARCIS"): "Closure/accreditation loss",
        norm_name("Universidad los Leones"):
            "Closure/accreditation loss; extreme margins",
    }
    annual.insert(
        1,
        "Exclusion reason",
        annual["id_norm"].map(reason_by_norm),
    )

    variable_order = []
    for column in ["Acreditación (años)", "Matrícula pregrado", *OUTCOME_SPECS.keys()]:
        if column in annual.columns and column not in variable_order:
            variable_order.append(column)

    summary_rows = []
    for university, university_data in annual.groupby("id", sort=True):
        university_norm = university_data["id_norm"].iloc[0]
        for variable in variable_order:
            values = to_numeric_finite(university_data[variable])
            valid = values.notna()
            if not valid.any():
                continue
            years = university_data.loc[valid, "t"]
            summary_rows.append({
                "University": university,
                "Exclusion reason": reason_by_norm.get(university_norm, ""),
                "Variable": variable,
                "N": int(valid.sum()),
                "Mean": float(values.loc[valid].mean()),
                "Median": float(values.loc[valid].median()),
                "Std. dev.": float(values.loc[valid].std(ddof=1))
                if valid.sum() > 1 else np.nan,
                "Minimum": float(values.loc[valid].min()),
                "Maximum": float(values.loc[valid].max()),
                "First year": int(years.min()),
                "Last year": int(years.max()),
            })

    summary = pd.DataFrame(summary_rows)
    annual_output_columns = [
        "id", "Exclusion reason", "t", *variable_order
    ]
    annual_output = annual[annual_output_columns].rename(columns={
        "id": "University",
        "t": "Year",
    })

    output_path = os.path.join(
        SUMMARY_DIR,
        "Table_Excluded_Universities_Descriptive.xlsx",
    )
    with pd.ExcelWriter(output_path) as writer:
        summary.to_excel(writer, sheet_name="Summary", index=False)
        annual_output.to_excel(writer, sheet_name="Annual data", index=False)

    return output_path


def add_static_controls(d):
    """Create the same baseline-relative controls used by the dynamic design."""
    out = d.copy()
    base_cols = [
        "id",
        "log_enrollment_undergrad",
        "eligibility_proxy_10",
        "accreditation_years",
        "eligibility_coverage_10",
    ]
    baseline = out.loc[out["t"].eq(BASE_YEAR), base_cols].copy()

    if baseline["id"].duplicated().any():
        raise ValueError("More than one 2015 baseline row per university in static DiD.")

    baseline = baseline.rename(columns={
        "log_enrollment_undergrad": "_base_log_enrollment",
        "eligibility_proxy_10": "_base_eligibility_proxy_10",
        "accreditation_years": "_base_accreditation_years",
        "eligibility_coverage_10": "_base_eligibility_coverage_10",
    })

    out = out.merge(baseline, on="id", how="left", validate="many_to_one")
    out["post"] = (out["t"] >= TREAT_YEAR).astype(int)
    out["did"] = out["post"] * out["treated"]
    out["dlog_enrollment"] = (
        out["log_enrollment_undergrad"] - out["_base_log_enrollment"]
    )
    out["deligibility_proxy_10"] = (
        out["eligibility_proxy_10"] - out["_base_eligibility_proxy_10"]
    )
    out["daccreditation_years"] = (
        out["accreditation_years"] - out["_base_accreditation_years"]
    )
    out["deligibility_coverage_10"] = (
        out["eligibility_coverage_10"] - out["_base_eligibility_coverage_10"]
    )
    return out


def fit_static_did(d, specification):
    """Static pre/post DiD with university-clustered standard errors."""
    if specification not in {"basic", "twfe", "twfe_controls"}:
        raise ValueError(f"Unknown static DiD specification: {specification}")

    use = add_static_controls(d)
    required = ["y", "id", "t", "treated", "post", "did"]
    if specification == "twfe_controls":
        required += STATIC_CONTROL_COLS

    use = use.replace([np.inf, -np.inf], np.nan).dropna(subset=required).copy()
    if use.empty or use["treated"].nunique() < 2:
        return None

    y = to_numeric_finite(use["y"]).astype(float)

    if specification == "basic":
        X = use[["post", "treated", "did"]].astype(float).copy()
    else:
        parts = [use[["did"]].astype(float)]
        if specification == "twfe_controls":
            parts.append(use[STATIC_CONTROL_COLS].astype(float))
        id_fe = pd.get_dummies(use["id"], prefix="univ", drop_first=True, dtype=float)
        year_fe = pd.get_dummies(use["t"].astype(int), prefix="year", drop_first=True, dtype=float)
        parts.extend([id_fe, year_fe])
        X = pd.concat(parts, axis=1)

    X = sm.add_constant(X, has_constant="add")
    groups = pd.factorize(use["id"])[0]
    n_clusters = int(pd.Series(groups).nunique())
    if n_clusters < 2:
        return None

    try:
        result = sm.OLS(y, X, missing="drop").fit(
            cov_type="cluster",
            cov_kwds={"groups": groups, "use_correction": True},
        )
    except Exception as exc:
        return {"status": f"error: {exc}"}

    if "did" not in result.params.index:
        return {"status": "did coefficient absorbed or unavailable"}

    return {
        "status": "ok",
        "coef": float(result.params["did"]),
        "se": float(result.bse["did"]),
        "pvalue": float(result.pvalues["did"]),
        "ci_low": float(result.conf_int().loc["did", 0]),
        "ci_high": float(result.conf_int().loc["did", 1]),
        "nobs": int(result.nobs),
        "n_clusters": n_clusters,
        "adj_r2": float(result.rsquared_adj),
    }


def collect_static_did_results(panel, cohorts_norm, transformed=False):
    rows = []
    for sample_key, sample_label, exclude_closed in STATIC_SAMPLE_ORDER:
        for outcome in OUTCOME_SPECS:
            d = make_analysis_df(
                panel,
                outcome,
                cohorts_norm,
                exclude_closed=exclude_closed,
            )
            if d.empty or not d["y"].notna().any():
                continue

            transform_label = "level"
            if transformed:
                d, _, transform_label, _ = make_transformed_outcome(d, outcome)

            for spec_key, spec_label in STATIC_SPEC_ORDER:
                fit = fit_static_did(d, spec_key)
                row = {
                    "outcome": outcome,
                    "scale": transform_label if transformed else "level",
                    "sample": sample_key,
                    "sample_label": sample_label,
                    "specification": spec_key,
                    "specification_label": spec_label,
                }
                if fit is None:
                    row.update({
                        "status": "not estimable",
                        "coef": np.nan,
                        "se": np.nan,
                        "pvalue": np.nan,
                        "ci_low": np.nan,
                        "ci_high": np.nan,
                        "nobs": 0,
                        "n_clusters": 0,
                        "adj_r2": np.nan,
                    })
                else:
                    row.update(fit)
                rows.append(row)
    return pd.DataFrame(rows)


def _stars(pvalue):
    if pd.isna(pvalue):
        return ""
    if pvalue < 0.01:
        return "***"
    if pvalue < 0.05:
        return "**"
    if pvalue < 0.10:
        return "*"
    return ""


def _did_paper_matrix(results):
    column_defs = []
    for sample_key, sample_label, _ in STATIC_SAMPLE_ORDER:
        for spec_key, spec_label in STATIC_SPEC_ORDER:
            column_defs.append(
                (
                    sample_key,
                    spec_key,
                    f"{sample_label}: {spec_label}",
                )
            )
    spec_labels = [x[2] for x in column_defs]
    records = []
    for outcome in OUTCOME_SPECS:
        sub = results.loc[results["outcome"].eq(outcome)]
        if sub.empty:
            continue

        coef_row = {"Outcome / statistic": outcome}
        se_row = {"Outcome / statistic": "(SE)"}
        n_row = {"Outcome / statistic": "Observations"}
        r2_row = {"Outcome / statistic": "Adjusted R2"}

        for sample_key, spec_key, spec_label in column_defs:
            r = sub.loc[
                sub["sample"].eq(sample_key)
                & sub["specification"].eq(spec_key)
            ]
            if r.empty or r.iloc[0].get("status") != "ok":
                coef_row[spec_label] = "--"
                se_row[spec_label] = ""
                n_row[spec_label] = "--"
                r2_row[spec_label] = "--"
                continue
            rr = r.iloc[0]
            coef_row[spec_label] = f'{rr["coef"]:.3f}{_stars(rr["pvalue"])}'
            se_row[spec_label] = f'({rr["se"]:.3f})'
            n_row[spec_label] = str(int(rr["nobs"]))
            r2_row[spec_label] = f'{rr["adj_r2"]:.3f}'

        records.extend([coef_row, se_row, n_row, r2_row])

    records.extend([
        {
            "Outcome / statistic": "University FE",
            **{
                label: ("No" if spec_key == "basic" else "Yes")
                for _, spec_key, label in column_defs
            },
        },
        {
            "Outcome / statistic": "Year FE",
            **{
                label: ("No" if spec_key == "basic" else "Yes")
                for _, spec_key, label in column_defs
            },
        },
        {
            "Outcome / statistic": "Controls",
            **{
                label: ("Yes" if spec_key == "twfe_controls" else "No")
                for _, spec_key, label in column_defs
            },
        },
        {
            "Outcome / statistic": "SE clustered by university",
            **{label: "Yes" for _, _, label in column_defs},
        },
    ])
    return pd.DataFrame(records, columns=["Outcome / statistic", *spec_labels])


