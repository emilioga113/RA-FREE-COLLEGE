def plot_levels(
    d,
    outcome,
    transformed=False,
    transform_label=None,
):
    if plt is None:
        return None

    apply_qtt_style()

    df = d.copy()

    df["event_time_ctrl"] = (
        df["t"]
        - TREAT_YEAR
    )

    treated = (
        df.loc[
            df["treated"] == 1
        ]
        .groupby("event_time")["y"]
        .mean()
        .reset_index()
    )

    control = (
        df.loc[
            df["treated"] == 0
        ]
        .groupby("event_time_ctrl")["y"]
        .mean()
        .reset_index()
        .rename(
            columns={
                "event_time_ctrl": "event_time"
            }
        )
    )

    treated = treated[
        treated["event_time"].between(
            WINDOW[0],
            WINDOW[1],
        )
    ]

