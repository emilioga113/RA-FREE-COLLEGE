# CHANGE REGRESSION
# ============================================================

def fit_change_regression(sub, regressors):
    use = sub.dropna(
        subset=["dy", "treated"] + regressors
    ).copy()

    n_treated = int(
        (use["treated"] == 1).sum()
    )

    n_control = int(
        (use["treated"] == 0).sum()
    )

    empty_coefs = {
        name: np.nan
        for name in regressors
    }

    if n_treated == 0 or n_control == 0:
        return (
            np.nan,
            empty_coefs,
            n_treated,
            n_control,
            "no valid treated/control",
        )

    x = np.column_stack([
        np.ones(len(use)),
        use["treated"].to_numpy(dtype=float),
        *[
            use[name].to_numpy(dtype=float)
            for name in regressors
        ],
    ])

    if np.linalg.matrix_rank(x) < x.shape[1]:
        return (
            np.nan,
            empty_coefs,
            n_treated,
            n_control,
            "singular regression",
        )

    y = use["dy"].to_numpy(
        dtype=float
    )

    coef = np.linalg.lstsq(
        x,
        y,
        rcond=None,
    )[0]

    control_coefs = {
        name: float(coef[j + 2])
        for j, name in enumerate(regressors)
    }

    return (
        float(coef[1]),
        control_coefs,
        n_treated,
        n_control,
        "ok",
    )


