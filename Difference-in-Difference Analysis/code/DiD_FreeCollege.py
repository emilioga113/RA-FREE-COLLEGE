def plot_dynamic(
    ev,
    outcome,
    transformed=False,
    transform_label=None,
):
    """
    Plot style:
    - solid black ATT
    - black circular markers
    - dashed lower/upper confidence intervals
    - no shaded confidence band
    - horizontal zero line
    - vertical treatment line at event time 0
    - sample size under each event-time estimate
    """

    if plt is None or ev is None or ev.empty:
        return None

    apply_qtt_style()

    ev = (
        ev.sort_values("event_time")
        .copy()
    )

    fig, ax = plt.subplots()

    # --------------------------------------------------------
    # REFERENCE LINES
    # --------------------------------------------------------

    ax.axhline(
        0,
        linewidth=1.8,
        color="black",
        zorder=2,
    )

    ax.axvline(
        0,
        linestyle="--",
        linewidth=1.4,
        color="black",
        zorder=2,
    )

    # --------------------------------------------------------
    # ATT
    # --------------------------------------------------------

    ax.plot(
        ev["event_time"],
        ev["att"],
        marker="o",
        markersize=7,
        linewidth=2.5,
        color="black",
        zorder=4,
    )

    # --------------------------------------------------------
    # CONFIDENCE INTERVALS
    # --------------------------------------------------------

    valid_ci = (
        np.isfinite(
            pd.to_numeric(
                ev["ci_low"],
                errors="coerce",
            )
        )
        &
        np.isfinite(
            pd.to_numeric(
                ev["ci_high"],
                errors="coerce",
            )
        )
    )

    if valid_ci.any():
        ci = ev.loc[valid_ci]

        # Lower CI
        ax.plot(
            ci["event_time"],
            ci["ci_low"],
            linestyle=(0, (5, 5)),
            linewidth=1.9,
            color="black",
            zorder=3,
        )

        # Upper CI
        ax.plot(
            ci["event_time"],
            ci["ci_high"],
            linestyle=(0, (5, 5)),
            linewidth=1.9,
            color="black",
            zorder=3,
        )

    # --------------------------------------------------------
    # X AXIS
    # --------------------------------------------------------

    ax.set_xticks(
        np.arange(
            WINDOW[0],
            WINDOW[1] + 1,
            1,
        )
    )

    ax.set_xlim(
        WINDOW[0] - 0.5,
        WINDOW[1] + 0.5,
    )

    if FuncFormatter is not None:
        ax.yaxis.set_major_formatter(
            FuncFormatter(
                smart_number_formatter
            )
        )

    # --------------------------------------------------------
    # SAMPLE SIZE UNDER X AXIS
    # --------------------------------------------------------

    for _, row in ev.iterrows():
        n_treated = row.get(
            "n_treated",
            0,
        )

        n_control = row.get(
            "n_control",
            0,
        )

        try:
            n = (
                int(n_treated)
                + int(n_control)
            )
        except (TypeError, ValueError):
            continue

        ax.text(
            row["event_time"],
            -0.18,
            f"n={n}",
            transform=ax.get_xaxis_transform(),
            ha="center",
            va="top",
            fontsize=9.5,
            color="black",
            clip_on=False,
        )

    # --------------------------------------------------------
    # TITLES
    # --------------------------------------------------------

    if transformed and transform_label:
        title = (
            f"Dynamic DiD - "
            f"{outcome} - "
            f"{transform_label}"
        )
    else:
        title = (
            f"Dynamic DiD - {outcome}"
        )

    ax.set_title(
        title,
        loc="left",
        pad=8,
    )

    fig.suptitle(
        (
            "Control: never-treated | "
            f"Cohort: {TREAT_YEAR} | "
            f"Event-study reference: {EVENT_BASE_YEAR}"
        ),
        x=0.5,
        y=0.985,
        ha="center",
        fontsize=14,
    )

    ax.set_xlabel(
        "Event time"
    )

    ax.set_ylabel(
        "Treatment effect"
    )

    # Enough room for n=... labels.
    fig.subplots_adjust(
        left=0.10,
        right=0.98,
        top=0.84,
        bottom=0.23,
    )

    folder = (
        PLOTS_LOG_DIR
        if transformed
        else PLOTS_DIR
    )

    prefix = (
        "event_log_dynamic"
        if transformed
        else "event_dynamic"
    )

    path = os.path.join(
        folder,
        f"{prefix}_{safe(outcome)}.png",
    )

    plt.savefig(
        path,
        dpi=FIG_DPI,
        bbox_inches="tight",
    )

    plt.close(fig)

    return path


