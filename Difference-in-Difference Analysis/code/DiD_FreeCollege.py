def compute_att_dynamic(d):
    change_frames, msg = (
        prepare_dynamic_changes(d)
    )

    if not change_frames:
        return (
            pd.DataFrame(),
            msg,
        )

    rows = []

    for tau in sorted(change_frames):
        year = change_frames[
            tau
        ]["year"]

        sub = change_frames[
            tau
        ]["data"]

        (
            att,
            beta,
            n_treated,
            n_control,
            status,
        ) = fit_change_regression(
            sub,
            MAIN_CONTROLS,
        )

        (
            att_enrollment,
            _,
            nt_enrollment,
            nc_enrollment,
            status_enrollment,
        ) = fit_change_regression(
            sub,
            ENROLLMENT_ONLY_CONTROLS,
        )

        (
            att_ge4,
            _,
            nt_ge4,
            nc_ge4,
            status_ge4,
        ) = fit_change_regression(
            sub,
            DUMMY_ACCREDITATION_CONTROLS,
        )

        rows.append({
            "year": year,
            "event_time": tau,
            "att": att,
            "att_enrollment_only": att_enrollment,
            "att_accreditation_ge4": att_ge4,
            "beta_dlog_enrollment": beta.get(
                "dlog_enrollment",
                np.nan,
            ),
            "beta_deligibility_proxy_10": beta.get(
                "deligibility_proxy_10",
                np.nan,
            ),
            "beta_daccreditation_years": beta.get(
                "daccreditation_years",
                np.nan,
            ),
            "beta_deligibility_coverage_10": beta.get(
                "deligibility_coverage_10",
                np.nan,
            ),
            "n_treated": n_treated,
            "n_control": n_control,
            "n_treated_enrollment_only": nt_enrollment,
            "n_control_enrollment_only": nc_enrollment,
            "n_treated_accreditation_ge4": nt_ge4,
            "n_control_accreditation_ge4": nc_ge4,
            "status": status,
            "status_enrollment_only": status_enrollment,
            "status_accreditation_ge4": status_ge4,
            "se_boot": np.nan,
            "ci_low": np.nan,
            "ci_high": np.nan,
            "boot_reps_valid": 0,
        })

    return (
        pd.DataFrame(rows)
        .sort_values("event_time"),
        "ok",
    )


