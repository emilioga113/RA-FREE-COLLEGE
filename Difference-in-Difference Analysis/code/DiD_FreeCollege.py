def _latex_escape(text):
    replacements = {
        "\\": r"\textbackslash{}",
        "&": r"\&",
        "%": r"\%",
        "$": r"\$",
        "#": r"\#",
        "_": r"\_",
        "{": r"\{",
        "}": r"\}",
    }
    out = str(text)
    for old, new in replacements.items():
        out = out.replace(old, new)
    return out


def _summary_stats(series):
    s = to_numeric_finite(series).dropna()
    if s.empty:
        return {"mean": np.nan, "median": np.nan, "sd": np.nan, "n": 0}
    return {
        "mean": float(s.mean()),
        "median": float(s.median()),
        "sd": float(s.std(ddof=1)) if len(s) > 1 else np.nan,
        "n": int(s.count()),
    }


def _analysis_sample_base(panel, cohorts_norm):
    """One row per university-year using the same main DiD sample."""
    available_extras = [c for c in DESCRIPTIVE_EXTRA_COLS if c in panel.columns]
    cols = ["id", "id_norm", "t", *available_extras]
    base = panel[cols].drop_duplicates(subset=["id", "t"]).copy()

    excluded_norm = {
        norm_name(name)
        for name in (
            set(EXCLUDED_MAIN_SAMPLE)
            | set(EXCLUDED_CLOSED_UNIVERSITIES)
        )
    }
    base = base.loc[~base["id_norm"].isin(excluded_norm)].copy()
    base["actual_treatment_year"] = base["id_norm"].map(cohorts_norm)
    target = base["actual_treatment_year"].eq(TREAT_YEAR)
    never = base["actual_treatment_year"].isna()
    base = base.loc[target | never].copy()
    base["treated"] = base["actual_treatment_year"].eq(TREAT_YEAR).astype(int)
    base["post"] = (base["t"] >= TREAT_YEAR).astype(int)
    return base


