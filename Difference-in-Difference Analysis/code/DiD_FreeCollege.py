def merge_academic_outcomes(
    df,
    id_col,
    year_col,
    name_map,
    academic_file=ACADEMIC_OUTCOMES_FILE,
):
    """Merge Sabat's postgraduate outcomes without changing the Fitch panel.

    - Merge key: standardized university x year.
    - Row count/cardinality of the Fitch panel is preserved (many_to_one).
    - Existing Fitch columns are never overwritten.
    - If no external file is present, existing financial outcomes are unchanged.
    """
    out = df.copy()

    # If every academic outcome is already in the Fitch panel, no merge is needed.
    if all(col in out.columns for col in ACADEMIC_OUTCOME_COLS):
        print("[ACADEMIC] All postgraduate outcomes already exist in Fitch panel.")
        return out

    if academic_file is None:
        missing = [
            col for col in ACADEMIC_OUTCOME_COLS
            if col not in out.columns
        ]
        print(
            "[ACADEMIC] Optional postgraduate file not found. "
            "Financial outcomes are unchanged; missing academic outcomes "
            f"will be skipped: {missing}"
        )
        return out

    print(f"[ACADEMIC] Loading postgraduate outcomes: {academic_file}")
    academic = _read_academic_file(academic_file)

    academic_id = _pick_academic_id_col(academic)
    academic_year = _pick_academic_year_col(academic)

    academic = academic.copy()
    academic["_academic_id_std"] = apply_name_mapping(
        academic[academic_id].astype(str),
        name_map,
    )
    academic["_academic_year"] = (
        to_numeric_finite(academic[academic_year])
        .astype("Int64")
    )

    available = [
        col for col in ACADEMIC_OUTCOME_COLS
        if col in academic.columns
    ]
    missing_source = [
        col for col in ACADEMIC_OUTCOME_COLS
        if col not in academic.columns
    ]

    if not available:
        raise ValueError(
            "The academic outcomes file contains none of the expected columns:\n"
            + ", ".join(ACADEMIC_OUTCOME_COLS)
        )

    if missing_source:
        print(
            "[ACADEMIC] Columns absent from source and therefore skipped: "
            + ", ".join(missing_source)
        )

    keep = [
        "_academic_id_std",
        "_academic_year",
        *available,
    ]
    academic = academic[keep].copy()

    for col in available:
        academic[col] = to_numeric_finite(academic[col])

    # Validate one value per university-year for each academic outcome.
    grouped = academic.groupby(
        ["_academic_id_std", "_academic_year"],
        dropna=False,
    )

    conflicts = []
    for col in available:
        nunique = grouped[col].nunique(dropna=True)
        bad = nunique[nunique > 1]
        if len(bad):
            conflicts.extend(
                (col, idx)
                for idx in bad.index[:10]
            )

    if conflicts:
        raise ValueError(
            "Conflicting academic values for the same university-year. "
            f"Examples: {conflicts[:10]}"
        )

    academic = (
        academic
        .groupby(
            ["_academic_id_std", "_academic_year"],
            as_index=False,
            dropna=False,
        )[available]
        .first()
    )

    # Do not overwrite any identically named column that already exists.
    merge_cols = [
        col for col in available
        if col not in out.columns
    ]

    if not merge_cols:
        print("[ACADEMIC] No new academic columns need to be merged.")
        return out

    before_n = len(out)

    out = out.merge(
        academic[
            [
                "_academic_id_std",
                "_academic_year",
                *merge_cols,
            ]
        ],
        left_on=[id_col, year_col],
        right_on=["_academic_id_std", "_academic_year"],
        how="left",
        validate="many_to_one",
    )

    out = out.drop(
        columns=[
            "_academic_id_std",
            "_academic_year",
        ]
    )

    if len(out) != before_n:
        raise RuntimeError(
            "Academic merge changed the Fitch panel row count."
        )

    print(
        "[ACADEMIC] Merged outcomes: "
        + ", ".join(merge_cols)
    )

    # Shares are preserved exactly as supplied. Warn, never rescale automatically.
    for col in [
        "posgrado_share",
        "share_health_posgrado",
        "share_social_posgrado",
    ]:
        if col in out.columns:
            s = to_numeric_finite(out[col])
            if s.notna().any() and (s.abs() > 1.05).any():
                print(
                    f"[ACADEMIC WARNING] {col} contains values with |share| > 1.05. "
                    "No automatic /100 conversion was applied."
                )

    return out


