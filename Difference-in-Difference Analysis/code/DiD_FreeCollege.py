# GRAPH NUMBER FORMATTER
# ============================================================

def smart_number_formatter(x, pos=None):
    if pd.isna(x) or not np.isfinite(x):
        return ""

    ax = abs(x)

    if ax == 0:
        return "0"

    if ax < 1:
        return (
            f"{x:.3f}"
            .rstrip("0")
            .rstrip(".")
        )

    if ax < 10:
        return (
            f"{x:.2f}"
            .rstrip("0")
            .rstrip(".")
        )

    if ax < 100:
        return (
            f"{x:.1f}"
            .rstrip("0")
            .rstrip(".")
        )

    return (
        f"{int(round(x)):,}"
        .replace(",", ".")
    )


