def _read_academic_file(path):
    ext = os.path.splitext(path)[1].lower()

    if ext == ".csv":
        return pd.read_csv(path, encoding="utf-8-sig")

    if ext in {".xlsx", ".xls"}:
        return pd.read_excel(path)

    raise ValueError(
        "Academic outcomes file must be CSV or Excel (.csv, .xlsx, .xls):\n"
        f"{path}"
    )


def _pick_academic_id_col(df):
    candidates = [
        "Universidad_std",
        "Universidad",
        "universidad",
        "Institución",
        "Institucion",
        "institucion",
        "university",
        "University",
    ]

    for col in candidates:
        if col in df.columns:
            return col

    raise ValueError(
        "No university identifier found in the academic outcomes file. "
        f"Expected one of: {candidates}"
    )


