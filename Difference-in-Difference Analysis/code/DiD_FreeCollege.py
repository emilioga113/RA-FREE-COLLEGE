# CHANGES RELATIVE TO THE EVENT-STUDY REFERENCE YEAR
# ============================================================

def prepare_dynamic_changes(d):
    index_cols = [
        "id",
        "id_norm",
        "treated",
    ]

    def pivot(variable, prefix):
        out = (
            d.pivot_table(
                index=index_cols,
                columns="t",
                values=variable,
                aggfunc="first",
            )
            .reset_index()
        )

        rename = {
            c: f"{prefix}_{int(c)}"
            for c in out.columns
            if isinstance(c, (int, np.integer))
        }

        return out.rename(
            columns=rename
        )

    wide = pivot(
        "y",
        "y",
    )

    control_pivots = [
        (
            "log_enrollment_undergrad",
            "m",
        ),
        (
            "eligibility_proxy_10",
            "e",
        ),
        (
            "accreditation_years",
            "a",
        ),
        (
            "accreditation_ge4",
            "a4",
        ),
        (
            "eligibility_coverage_10",
            "c",
        ),
    ]

    for variable, prefix in control_pivots:
        wide = wide.merge(
            pivot(variable, prefix),
            on=index_cols,
            how="outer",
        )

    base_y = f"y_{EVENT_BASE_YEAR}"

    if base_y not in wide.columns:
        return (
            {},
            "Base outcome unavailable.",
        )

    years = sorted(
        int(
            c.replace("y_", "")
        )
        for c in wide.columns
        if (
            isinstance(c, str)
            and c.startswith("y_")
        )
    )

    change_frames = {}

    for year in years:
        tau = year - TREAT_YEAR

        if not (
            WINDOW[0]
            <= tau
            <= WINDOW[1]
        ):
            continue

        # 2013 (event time -3) is the omitted baseline. Event times -2 and -1
        # therefore display possible anticipation in 2014 and 2015.
        if year == EVENT_BASE_YEAR:
            continue

        year_y = f"y_{year}"

        needed = {
            base_y,
            year_y,
            f"m_{EVENT_BASE_YEAR}",
            f"m_{year}",
            f"e_{EVENT_BASE_YEAR}",
            f"e_{year}",
            f"a_{EVENT_BASE_YEAR}",
            f"a_{year}",
            f"a4_{EVENT_BASE_YEAR}",
            f"a4_{year}",
            f"c_{EVENT_BASE_YEAR}",
            f"c_{year}",
        }

        sub = wide[
            [
                "id",
                "treated",
            ]
        ].copy()

        for col in needed:
            sub[col] = (
                wide[col]
                if col in wide.columns
                else np.nan
            )

        sub["dy"] = (
            sub[year_y]
            - sub[base_y]
        )

        sub["dlog_enrollment"] = (
            sub[f"m_{year}"]
            - sub[f"m_{EVENT_BASE_YEAR}"]
        )

        sub["deligibility_proxy_10"] = (
            sub[f"e_{year}"]
            - sub[f"e_{EVENT_BASE_YEAR}"]
        )

        sub["daccreditation_years"] = (
            sub[f"a_{year}"]
            - sub[f"a_{EVENT_BASE_YEAR}"]
        )

        sub["daccreditation_ge4"] = (
            sub[f"a4_{year}"]
            - sub[f"a4_{EVENT_BASE_YEAR}"]
        )

        sub["deligibility_coverage_10"] = (
            sub[f"c_{year}"]
            - sub[f"c_{EVENT_BASE_YEAR}"]
        )

        change_frames[tau] = {
            "year": year,
            "data": sub,
        }

    return (
        change_frames,
        "ok",
    )


