# TREATMENT COHORTS
# ============================================================

def load_treatment_cohorts(path, mapping):
    """
    The cohort database identifies all treated universities,
    especially later-treated units that must not be controls.

    The 2016 cohort is imposed directly from TREATED_2016.
    """

    if not os.path.exists(path):
        raise FileNotFoundError(
            f"No se encuentra la clasificación de cohortes:\n{path}"
        )

    cohorts = pd.read_csv(path, encoding="utf-8-sig")

    columns = {
        norm_name(c): c
        for c in cohorts.columns
    }

    university_col = (
        columns.get("universidad")
        or columns.get("institucion")
    )

    category_col = columns.get("categoria")
    year_col = columns.get("ano")

    if not all([university_col, category_col, year_col]):
        raise ValueError(
            "Faltan Universidad/Institución, Categoria o Año "
            "en la clasificación de gratuidad."
        )

    treated = cohorts[
        pd.to_numeric(
            cohorts[category_col],
            errors="coerce",
        ).eq(1)
    ].copy()

    treated[year_col] = pd.to_numeric(
        treated[year_col],
        errors="coerce",
    )

    treated = treated.dropna(
        subset=[
            university_col,
            year_col,
        ]
    )

    out = {}

    for _, row in treated.iterrows():
        raw_name = str(row[university_col]).strip()

        standard = mapping.get(
            norm_name(raw_name),
            raw_name,
        )

        key = norm_name(standard)
        year = int(row[year_col])

        if key in out and out[key] != year:
            raise ValueError(
                f"Cohortes incompatibles para {standard}: "
                f"{out[key]} y {year}."
            )

        out[key] = year

    forced_2016 = normalize_cohort_dict(
        TREATED_2016,
        mapping,
    )

    for key, year in forced_2016.items():
        if key in out and out[key] != year:
            print(
                f"[OVERRIDE] {key}: "
                f"{out[key]} -> {year}"
            )

        out[key] = year

    return out


